"""Turn a published Claude artifact into a page this site can serve.

The artifact platform wraps a published page in its own skeleton and leaves the page's real
<title> and font <link> sitting AFTER <body> opens. Browsers forgive that and it renders, but
on our own domain those belong in the actual <head>, next to the things an artifact never
carries: a description, share-card tags, a canonical URL and a favicon.

That patch is identical every time, so it is a script rather than a habit. Run it again after
every re-export and the page comes out the same, with no chance of losing the canonical tag at
midnight.

    python export_artifact.py in.html out.html --slug circles \
        --title "Circles All the Way Down" --desc "..." --version 1788731177-b7e9

Notes
  * URLs on this site end in .html. Every entry in catalog.js does, so /circles.html it is.
  * The way back to the site is the kit's own guest bar, not a hand-rolled corner link:
    one script tag, and the page gets the same slim bar every other imported tool has.
"""
import argparse
import re
import sys

SITE = "https://fluidta.com"


def patch(html, slug, title, desc, version, card=None):
    # The page's real <title> and stylesheet links sit after <body>; lift them into <head>.
    body_at = html.find("<body>")
    if body_at < 0:
        sys.exit("no <body> found - is this an exported artifact?")
    head_end = html.find("</head>")
    if head_end < 0 or head_end > body_at:
        sys.exit("no </head> before <body> - unexpected shape")

    tail = html[body_at:]
    hoisted = []

    m = re.search(r"<title>.*?</title>", tail, re.S)
    if m:
        hoisted.append(m.group(0))
        tail = tail[: m.start()] + tail[m.end():]

    # only the links sitting in the first stretch after <body>, which is where the wrapper
    # strands them; anything further down belongs to the page itself and is left alone
    for m in list(re.finditer(r"<link\b[^>]*>", tail[:4000]))[::-1]:
        hoisted.append(m.group(0))
        tail = tail[: m.start()] + tail[m.end():]
    hoisted.reverse()

    if not any("<title>" in h for h in hoisted):
        hoisted.insert(0, "<title>%s</title>" % title)

    url = "%s/%s.html" % (SITE, slug)
    meta = [
        '<meta name="description" content="%s">' % desc,
        '<link rel="canonical" href="%s">' % url,
        '<link rel="icon" href="/favicon.svg" type="image/svg+xml">',
        '<meta property="og:type" content="website">',
        '<meta property="og:site_name" content="FluidTA">',
        '<meta property="og:title" content="%s">' % title,
        '<meta property="og:description" content="%s">' % desc,
        '<meta property="og:url" content="%s">' % url,
        '<meta name="twitter:title" content="%s">' % title,
        '<meta name="twitter:description" content="%s">' % desc,
    ]
    if card:
        meta += [
            '<meta property="og:image" content="%s/%s">' % (SITE, card),
            '<meta name="twitter:card" content="summary_large_image">',
            '<meta name="twitter:image" content="%s/%s">' % (SITE, card),
        ]
    else:
        # A card tag pointing at an image that is not there is worse than none: the scrape
        # fails instead of falling back.
        meta.append('<meta name="twitter:card" content="summary">')

    # the kit's guest bar: the way back to the rest of the site
    meta.append('<script src="/fta.js" data-guest defer></script>')

    stamp = "<!-- exported from artifact version %s; edit the artifact, re-run " \
            "export_artifact.py, commit. Do not edit this file by hand. -->\n" % version

    out = (stamp
           + html[:head_end]
           + "\n" + "\n".join(hoisted + meta) + "\n"
           + html[head_end:body_at]
           + tail)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("dst")
    ap.add_argument("--slug", required=True)
    ap.add_argument("--title", required=True)
    ap.add_argument("--desc", required=True)
    ap.add_argument("--version", required=True)
    ap.add_argument("--card", default=None, help="share-card image path, e.g. circles-card.png")
    a = ap.parse_args()

    with open(a.src, encoding="utf-8") as f:
        html = f.read()
    out = patch(html, a.slug, a.title, a.desc, a.version, a.card)
    with open(a.dst, "w", encoding="utf-8") as f:
        f.write(out)

    head = out[: out.find("</head>")]
    print("[OK] wrote %s (%d bytes)" % (a.dst, len(out)))
    print("     title in head: %s" % ("<title>" in head))
    print("     font link in head: %s" % ("fonts.googleapis" in head))
    print("     canonical in head: %s" % ("rel=\"canonical\"" in head))
    print("     guest bar: %s" % ("data-guest" in head))


if __name__ == "__main__":
    main()
