export function haversine(lat1, lon1, lat2, lon2) {
  const dlat = (lat2 - lat1) * DEG, dlon = (lon2 - lon1) * DEG;
  const a = Math.sin(dlat / 2) ** 2 +
    Math.cos(lat1 * DEG) * Math.cos(lat2 * DEG) * Math.sin(dlon / 2) ** 2;
  return R_EARTH * 2 * Math.asin(Math.sqrt(a));
}

export function bearingTo(lat1, lon1, lat2, lon2) {
  const dlon = (lon2 - lon1) * DEG;
  const y = Math.sin(dlon) * Math.cos(lat2 * DEG);
  const x = Math.cos(lat1 * DEG) * Math.sin(lat2 * DEG) -
    Math.sin(lat1 * DEG) * Math.cos(lat2 * DEG) * Math.cos(dlon);
  return (Math.atan2(y, x) / DEG + 360) % 360;
}

/* How far above level a summit appears, in degrees, with the curvature drop taken out. */
export function angularElevation(distM, peakElevM, eyeElevM) {
  const drop = (distM * distM) / (2 * R_EARTH) * (1 - REFRACTION_K);
  return Math.atan2(peakElevM - drop - eyeElevM, distM) / DEG;
}

/* The peaks worth drawing from a given eye position.

   `maxKm` is a seeing limit, not a geometric one: Blanca Peak is 240 km from Denver and is
   genuinely visible a few days a year, but drawing it every day would put a label on haze.
   Peaks whose computed elevation is below level are dropped, which is the curvature doing
   the work — it is why nothing from the Sangres shows up from a low spot on the plains. */
export function peaksFrom(lat, lon, eyeElevM, maxKm = 190) {
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return [];
  const eye = Number.isFinite(eyeElevM) ? eyeElevM : 1600;
  return RAW_PEAKS.map(p => {
    const dist = haversine(lat, lon, p.lat, p.lon);
    return {
      name: p.name, elev: p.elev,
      elevFt: Math.round(p.elev * 3.28084),
      distKm: dist / 1000,
      az: bearingTo(lat, lon, p.lat, p.lon),
      el: angularElevation(dist, p.elev, eye)
    };
  })
    /* 1.5 km is "you are standing on it", and the geometry degenerates there */
    .filter(p => p.distKm > 1.5 && p.distKm <= maxKm && p.el > 0.05)
    .sort((a, b) => b.distKm - a.distKm);     // far ones first, so near summits label over them
}

/* Is this a place these peaks are about? The box is Colorado plus a margin, because the
   Front Range is just as much a skyline from Cheyenne or Scottsbluff as from Denver. */
export function inPeakCountry(lat, lon) {
  return lat > 36.5 && lat < 41.6 && lon > -109.5 && lon < -101.5;
}
